"""
src/evaluation/vision_eval.py
────────────────────────────────
Scores the Vision Agent's extraction accuracy against the synthetic
ground-truth manifest generated by data/synthetic/generate_invoice_images.py.

This is the vision-side equivalent of ragas_eval.py for the RAG agent —
same spirit (measure accuracy against a known-good answer key), but much
lighter-weight: no RAGAS/judge-LLM dependency, since these are crisp
field-level comparisons (does the extracted PO number match?) rather than
open-ended answer-quality scoring.

Run:
    python data/synthetic/generate_invoice_images.py   # once, to create test images
    python src/evaluation/vision_eval.py
"""

import sys
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from dotenv import load_dotenv
load_dotenv()

from src.agents.vision_agent import VisionAgent


MANIFEST_PATH = ROOT / "data" / "synthetic" / "invoices" / "manifest.json"


def _fuzzy_match(a: str, b: str) -> bool:
    """
    Loose string comparison — case/whitespace-insensitive substring match.
    Good enough for vendor names the VLM may transcribe with tiny
    formatting differences (e.g. trailing "Inc." vs "Inc").
    """
    a, b = (a or "").strip().lower(), (b or "").strip().lower()
    if not a or not b:
        return False
    return a == b or a in b or b in a


def _amount_close(a, b, tolerance: float = 0.02) -> bool:
    """Within 2% of the ground-truth total (rounding/OCR tolerance)."""
    if a is None or b is None:
        return False
    try:
        return abs(float(a) - float(b)) <= tolerance * max(abs(float(b)), 1.0)
    except (TypeError, ValueError):
        return False


def run_vision_eval():
    if not MANIFEST_PATH.exists():
        print(f"No manifest found at {MANIFEST_PATH}.")
        print("Run: python data/synthetic/generate_invoice_images.py")
        return

    manifest = json.loads(MANIFEST_PATH.read_text())
    agent = VisionAgent()

    print("\n" + "=" * 60)
    print(f"VISION AGENT EVAL — {len(manifest)} synthetic invoice images")
    print("=" * 60)

    fields   = ["vendor_name", "po_number", "invoice_number", "total_amount"]
    scores   = {f: 0 for f in fields}
    total    = 0
    failures = []

    for entry in manifest:
        image_path = ROOT / entry["file"]
        gt = entry["ground_truth"]

        with open(image_path, "rb") as f:
            image_bytes = f.read()

        result = agent.run(image_bytes)
        total += 1

        if not result.success:
            failures.append((entry["file"], "extraction failed", result.error))
            continue

        checks = {
            "vendor_name"   : _fuzzy_match(result.vendor_name, gt["vendor_name"]),
            "po_number"     : _fuzzy_match(result.po_number, gt["po_number"]),
            "invoice_number": _fuzzy_match(result.invoice_number, gt["invoice_number"]),
            "total_amount"  : _amount_close(result.total_amount, gt["total_amount"]),
        }
        for field, ok in checks.items():
            if ok:
                scores[field] += 1
            else:
                got = getattr(result, field)
                failures.append((entry["file"], field, f"got={got!r} expected={gt[field]!r}"))

    print("\n--- Field-level accuracy ---")
    for field, correct in scores.items():
        pct = 100 * correct / total if total else 0
        print(f"  {field:16s}: {correct}/{total}  ({pct:.0f}%)")

    if failures:
        print(f"\n--- {len(failures)} mismatches ---")
        for file, field, detail in failures[:20]:
            print(f"  {file}: {field} — {detail}")

    print("\nDone.")


if __name__ == "__main__":
    run_vision_eval()
